function toIsoTime(time: string): string {
  return `2026-09-06T${time}:00.000Z`;
}

const EVENT_STREAM_ALERTS: Alert[] = EVENT_STREAM.map(
  (
    [id, status, title, location, timestamp, detail_line, link_text, type],
    i,
  ) => ({
    alert_id: id,
    type,
    severity:
      status === "error" ? "high" : status === "warning" ? "medium" : "low",
    status: status === "success" ? "resolved" : "investigating",
    title,
    detail: "",
    location: { label: "" },
    detected_at: `2026-09-05T${String(23 - Math.floor(i / 4)).padStart(2, "0")}:${String(
      (i * 17) % 60,
    ).padStart(2, "0")}:00.000Z`,
    event_stream: {
      status,
      title,
      location,
      timestamp,
      detail_line,
      link_text,
    },
  }),
);

const TRIAGE_ALERTS: Alert[] = TRIAGE.map(
  ([
    id,
    type,
    title,
    detail,
    locationLabel,
    time,
    severity,
    status,
    latitude,
    longitude,
  ]) => ({
    alert_id: id,
    type,
    severity,
    status,
    title,
    detail,
    location: {
      label: locationLabel,
      latitude,
      longitude,
    },
    detected_at: toIsoTime(time),
    involved_plate: /[A-Z0-9]{6,}/.test(detail) ? detail : undefined,
  }),
);

export const ALERTS: Alert[] = [...EVENT_STREAM_ALERTS, ...TRIAGE_ALERTS];
